// Run with: npm run encode
// Reads your real links from contact.local.json (never committed) and writes
// src/contact.generated.ts, which only contains encoded values.
// Layers: reverse, then XOR with a key, then Base64.
import { readFileSync, writeFileSync } from 'node:fs';

const KEY = 'gE-both-sides-2026';
const source = JSON.parse(readFileSync('contact.local.json', 'utf8'));

function encode(value) {
  const reversed = [...value].reverse().join('');
  const bytes = Array.from(new TextEncoder().encode(reversed), (byte, index) =>
    byte ^ KEY.charCodeAt(index % KEY.length),
  );
  return Buffer.from(bytes).toString('base64');
}

const output = `// Generated by scripts/encode-contacts.mjs. Do not edit by hand.
export const encodedContacts = {
  email: '${encode(source.email)}',
  whatsapp: '${encode(source.whatsapp)}',
  linkedin: '${encode(source.linkedin)}',
} as const;
`;

writeFileSync('src/contact.generated.ts', output);
console.log('Wrote src/contact.generated.ts');
